/**
 *  @brief Name of this component / task.
 */
const char *RequestHandlerBase::COMPONENT_NAME = "RequestHandlerBase";

/**
 *  @brief MessageDispatcher object that ensure that messages are delivered to
 *  the correct part of the system.
 */
IMessageDispatcher *RequestHandlerBase::_messageDispatcher = nullptr;

/*
 * ---------------------------------------------------------------------------
 *
 *                     Constructors and destructor
 *
 * ---------------------------------------------------------------------------
 */

/**
 *  @brief Constructor for the RequestHandlerBase class.
 */
RequestHandlerBase::RequestHandlerBase() : _queueHandle(nullptr), _taskHandle(nullptr)
{
}

/**
 *  @brief Create a new request handler object and ensure that
 *  the message dispatcher reference is set up correctly.
 *
 *  @param messageDispatcher
 *      Message dispatcher object that will allow communication
 *      with the STM32.
 */
RequestHandlerBase::RequestHandlerBase(IMessageDispatcher *messageDispatcher) : RequestHandlerBase()
{
    _messageDispatcher = messageDispatcher;
}

/**
 *  @brief Destructor for the RequestHandlerBase class.
 */
RequestHandlerBase::~RequestHandlerBase()
{
}


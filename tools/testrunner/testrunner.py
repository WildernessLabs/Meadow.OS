#!/usr/bin/env python3
"""
Meadow.OS hardware test runner (option A in the test runner plan: deterministic rules, no LLM).

Deploys each test app in the manifest to the attached board with the Meadow CLI, once for each of
its Mono modes, watches the app output for the TESTRUN contract, decides pass or fail, and writes
a run directory with the raw logs, one JSON file per test, events.jsonl and summary.md.

The runner only deploys apps.  It does not flash the OS, the runtime or the ESP32 firmware, and
it never changes a repository.  See README.md for the output contract and the manifest format.
"""

import argparse
import datetime
import json
import os
import re
import shlex
import signal
import subprocess
import sys
import threading
import time
import queue

import yaml

REPOSITORY_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_MANIFEST = os.path.join(REPOSITORY_ROOT, "tests", "managed", "manifest.yaml")
DEFAULT_RUNS_DIR = os.path.join(REPOSITORY_ROOT, "test-runs")

TESTRUN = re.compile(r"^TESTRUN (BEGIN|CASE|INFO|END)\b ?(.*)$")
CASE = re.compile(r"^(\S+) (PASS|FAIL|SKIP) (\d+) ?(.*)$")
END = re.compile(r"^failures=(\d+) cases=(\d+)")
SOURCE_PREFIX = re.compile(r"^(stdout|stderr|info|warn|error)> ?")

#
#   CLI output that ends a test early.  Matched against every line, with the source prefix removed.
#
CLI_FAILURES = [
    (re.compile(r"No device found|Access to the port .* is denied"), "port"),
    (re.compile(r"Timeout attempting|TimeoutException"), "cli-timeout"),
    (re.compile(r"App failed|Unhandled exception|Mono has been disabled|runtime is disabled", re.I), "crash"),
    (re.compile(r"Build FAILED|error CS\d+|error MSB\d+"), "build"),
]

#
#   Values that must never reach a log: WiFi credentials printed by an app.
#
REDACT = [
    (re.compile(r"(ssid=)\S+", re.I), r"\1<redacted>"),
    (re.compile(r"(passw(or)?d=)\S+", re.I), r"\1<redacted>"),
]


def now():
    return datetime.datetime.now().astimezone()


def redact(line):
    for pattern, replacement in REDACT:
        line = pattern.sub(replacement, line)
    return line


class Events:
    """Progress events: one JSON line each in events.jsonl, and a short line on the terminal."""

    def __init__(self, path):
        self.file = open(path, "a", encoding="utf-8")

    def emit(self, kind, message, **fields):
        record = {"time": now().isoformat(timespec="seconds"), "event": kind, "message": message}
        record.update(fields)
        self.file.write(json.dumps(record) + "\n")
        self.file.flush()
        print(f"[{now():%H:%M:%S}] {kind:14} {message}", flush=True)

    def close(self):
        self.file.close()


def git_state(path):
    """HEAD, branch and dirty state of a checkout, or None if it is not one."""
    if (path is None) or (not os.path.isdir(path)):
        return None
    try:
        head = subprocess.run(["git", "-C", path, "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()
        branch = subprocess.run(["git", "-C", path, "rev-parse", "--abbrev-ref", "HEAD"], capture_output=True, text=True).stdout.strip()
        status = subprocess.run(["git", "-C", path, "status", "--porcelain", "--untracked-files=no"], capture_output=True, text=True).stdout
    except (OSError, subprocess.CalledProcessError):
        return None
    return {"path": path, "head": head, "branch": branch, "dirty": bool(status.strip())}


def device_info(cli):
    """OS, runtime and coprocessor versions from 'meadow device info'."""
    try:
        result = subprocess.run(cli + ["device", "info"], capture_output=True, text=True, timeout=120)
    except (OSError, subprocess.TimeoutExpired) as ex:
        return {"error": str(ex)}
    info = {}
    for line in result.stdout.splitlines():
        match = re.match(r"\s*(OS|Runtime|Coprocessor|Hardware version|Serial number):\s*(\S+)", line)
        if match:
            info[match.group(1).lower().replace(" ", "_")] = match.group(2)
    if not info:
        info["error"] = (result.stdout + result.stderr).strip()[-500:]
    return info


def mono_config(options):
    """meadow.config.yaml for one mode.  No MonoControl section when there are no options."""
    text = "#\n#   Generated by tools/testrunner.\n#\nDevice:\n    Name: MeadowTests\n"
    if options:
        text += f"MonoControl:\n    Options: {options}\n"
    return text


def stop_process(process):
    """End the CLI and everything it started (the dotnet child keeps the serial port otherwise)."""
    if process.poll() is not None:
        return
    for sig, wait in ((signal.SIGINT, 5), (signal.SIGTERM, 5), (signal.SIGKILL, 5)):
        try:
            os.killpg(process.pid, sig)
        except ProcessLookupError:
            return
        try:
            process.wait(timeout=wait)
            return
        except subprocess.TimeoutExpired:
            continue


def read_lines(stream, lines):
    """Split CLI output on both \\r and \\n (progress output uses \\r) and queue each line."""
    pending = ""
    while True:
        chunk = stream.read1(4096) if hasattr(stream, "read1") else stream.read(4096)
        if not chunk:
            break
        pending += chunk.decode("utf-8", errors="replace")
        parts = re.split(r"\r\n|\r|\n", pending)
        pending = parts.pop()
        for part in parts:
            lines.put(part)
    if pending:
        lines.put(pending)
    lines.put(None)


def run_test(test, mode, mode_options, settings, run_dir, events):
    """Deploy and run one test app in one mode; return its result record."""
    name = f"{test['name']}-{mode}"
    test_dir = os.path.join(run_dir, name)
    os.makedirs(test_dir, exist_ok=True)
    config_path = os.path.join(test_dir, "meadow.config.yaml")
    with open(config_path, "w", encoding="utf-8") as config:
        config.write(mono_config(mode_options))

    project = os.path.join(REPOSITORY_ROOT, test["project"])
    timeout_s = test.get("timeout_s", settings["timeout_s"])
    expected_s = test.get("expected_s")
    known = test.get("known_failures", {}) or {}

    environment = dict(os.environ)
    environment["MEADOW_TEST_CONFIG"] = config_path
    environment["MEADOW_RUNTIME_DIR"] = settings["runtime_dir"]
    environment["MEADOW_CORE_DIR"] = settings["core_dir"]

    result = {
        "name": name, "test": test["name"], "mode": mode, "mono_options": mode_options,
        "project": test["project"], "started": now().isoformat(timespec="seconds"),
        "verdict": None, "kind": None, "detail": "", "begin": None, "end": None,
        "cases": [], "info": [], "counts": {}, "duration_s": None,
    }
    events.emit("test_started", f"{name} (timeout {timeout_s}s)", test=name)

    command = settings["cli"] + ["app", "run", project, "-p"]
    log_path = os.path.join(test_dir, "output.log")
    start = time.monotonic()
    process = subprocess.Popen(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT, env=environment,
                               cwd=os.path.dirname(project), start_new_session=True)
    lines = queue.Queue()
    reader = threading.Thread(target=read_lines, args=(process.stdout, lines), daemon=True)
    reader.start()

    failure = None
    last_progress = start
    with open(log_path, "w", encoding="utf-8") as log:
        while True:
            remaining = timeout_s - (time.monotonic() - start)
            if remaining <= 0:
                failure = ("timeout", f"no END after {timeout_s}s")
                break
            try:
                line = lines.get(timeout=min(remaining, 10))
            except queue.Empty:
                if time.monotonic() - last_progress >= 60:
                    last_progress = time.monotonic()
                    events.emit("progress", f"{name}: {len(result['cases'])} cases, {int(time.monotonic() - start)}s", test=name)
                continue
            if line is None:
                if result["end"] is None:
                    failure = ("crash" if result["begin"] else "deploy", f"CLI exited ({process.wait()}) before END")
                break
            line = redact(line)
            log.write(line + "\n")
            text = SOURCE_PREFIX.sub("", line.strip())
            match = TESTRUN.match(text)
            if match:
                kind, rest = match.group(1), match.group(2)
                if kind == "BEGIN":
                    result["begin"] = rest
                    events.emit("app_started", f"{name}: {rest}", test=name)
                elif kind == "INFO":
                    result["info"].append(rest)
                elif kind == "CASE":
                    case = CASE.match(rest)
                    if case is None:
                        result["info"].append("malformed CASE: " + rest)
                        continue
                    entry = {"name": case.group(1), "status": case.group(2), "ms": int(case.group(3)), "detail": case.group(4)}
                    if (entry["status"] == "FAIL") and (entry["name"] in known):
                        entry["status"] = "KNOWN"
                        entry["known_reason"] = known[entry["name"]]
                    result["cases"].append(entry)
                    if entry["status"] in ("FAIL", "KNOWN"):
                        events.emit("case_result", f"{name}: {entry['name']} {entry['status']} {entry['detail']}", test=name)
                elif kind == "END":
                    result["end"] = rest
                    break
                continue
            for pattern, kind in CLI_FAILURES:
                if pattern.search(text):
                    failure = (kind, text[:200])
                    break
            if failure is not None:
                break
        stop_process(process)
        reader.join(timeout=10)
        while True:
            try:
                line = lines.get_nowait()
            except queue.Empty:
                break
            if line is not None:
                log.write(redact(line) + "\n")

    result["duration_s"] = round(time.monotonic() - start, 1)
    counts = {}
    for case in result["cases"]:
        counts[case["status"]] = counts.get(case["status"], 0) + 1
    result["counts"] = counts

    #
    #   Verdict rules (README.md): failures and missing END lines are never upgraded.
    #
    if failure is not None:
        result["verdict"], result["kind"], result["detail"] = "fail", failure[0], failure[1]
    elif counts.get("FAIL", 0) > 0:
        result["verdict"], result["kind"] = "fail", "cases"
        result["detail"] = ", ".join(c["name"] for c in result["cases"] if c["status"] == "FAIL")[:500]
    else:
        end = END.match(result["end"] or "")
        reported_cases = int(end.group(2)) if end else -1
        reported_failures = int(end.group(1)) if end else -1
        if (end is None) or (reported_cases != len(result["cases"])) or (reported_failures != counts.get("KNOWN", 0)):
            result["verdict"], result["kind"] = "fail", "contract"
            result["detail"] = f"END '{result['end']}' does not match {len(result['cases'])} CASE lines"
        else:
            result["verdict"] = "pass"
    if (expected_s is not None) and (result["duration_s"] > 2 * expected_s):
        result["info"].append(f"slow: {result['duration_s']}s against an expected {expected_s}s")

    with open(os.path.join(test_dir, "result.json"), "w", encoding="utf-8") as out:
        json.dump(result, out, indent=2)
    events.emit("test_finished", f"{name}: {result['verdict'].upper()} {summary_counts(counts)} {result['duration_s']}s"
                + (f" ({result['kind']}: {result['detail']})" if result["kind"] else ""), test=name, verdict=result["verdict"])
    return result


def summary_counts(counts):
    return " ".join(f"{key.lower()}={counts[key]}" for key in ("PASS", "FAIL", "KNOWN", "SKIP") if key in counts)


def write_summary(run, results, path):
    lines = [f"# Test run {run['id']}", ""]
    device = run["device"]
    lines.append(f"- Board: {device.get('hardware_version', '?')}, OS {device.get('os', '?')}, runtime {device.get('runtime', '?')}, "
                 f"coprocessor {device.get('coprocessor', '?')}")
    for key, state in run["sources"].items():
        if state:
            lines.append(f"- {key}: {state['branch']} {state['head'][:11]}{' (dirty)' if state['dirty'] else ''}")
    lines.append(f"- Started {run['started']}, finished {run['finished']}")
    lines += ["", "| Test | Mode | Verdict | Pass | Fail | Known | Skip | Time |", "|---|---|---|---|---|---|---|---|"]
    for result in results:
        counts = result["counts"]
        verdict = result["verdict"] + (f" ({result['kind']})" if result["kind"] else "")
        lines.append(f"| {result['test']} | {result['mode']} | {verdict} | {counts.get('PASS', 0)} | {counts.get('FAIL', 0)} | "
                     f"{counts.get('KNOWN', 0)} | {counts.get('SKIP', 0)} | {result['duration_s']}s |")
    for result in results:
        notable = [c for c in result["cases"] if c["status"] in ("FAIL", "KNOWN")]
        if notable or result["kind"] or result["info"]:
            lines += ["", f"## {result['name']}", ""]
            if result["kind"]:
                lines.append(f"- **{result['kind']}:** {result['detail']}")
            for case in notable:
                reason = f" (known: {case['known_reason']})" if case["status"] == "KNOWN" else ""
                lines.append(f"- `{case['name']}` {case['status']}: {case['detail']}{reason}")
            for info in result["info"]:
                lines.append(f"- {info}")
    with open(path, "w", encoding="utf-8") as out:
        out.write("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--manifest", default=DEFAULT_MANIFEST, help="test manifest (default: tests/managed/manifest.yaml)")
    parser.add_argument("--test", action="append", default=[], metavar="NAME[:MODE]",
                        help="run only this test, optionally in one mode; may be repeated")
    parser.add_argument("--runs-dir", default=os.environ.get("MEADOW_TEST_RUNS_DIR", DEFAULT_RUNS_DIR),
                        help="where run directories are created (default: test-runs/ in the repository)")
    parser.add_argument("--list", action="store_true", help="list the tests and modes, then exit")
    args = parser.parse_args()

    with open(args.manifest, encoding="utf-8") as manifest_file:
        manifest = yaml.safe_load(manifest_file)
    modes = manifest.get("modes", {})
    selected = []
    for test in manifest["tests"]:
        for mode in test.get("modes", ["jit"]):
            if mode not in modes:
                sys.exit(f"Test {test['name']}: unknown mode {mode}")
            if args.test and not any((t == test["name"]) or (t == f"{test['name']}:{mode}") for t in args.test):
                continue
            selected.append((test, mode))
    if args.list or not selected:
        for test, mode in selected:
            print(f"{test['name']}:{mode}  {test['project']}  options='{modes[mode].get('options', '')}'")
        if not selected:
            sys.exit("No tests selected.")
        return 0

    settings = dict(manifest.get("defaults", {}))
    settings.setdefault("timeout_s", 900)
    settings["cli"] = shlex.split(os.environ.get("MEADOW_CLI", "meadow"))
    settings["runtime_dir"] = os.path.abspath(os.environ.get("MEADOW_RUNTIME_DIR", os.path.join(REPOSITORY_ROOT, "..", "runtime")))
    settings["core_dir"] = os.path.abspath(os.environ.get("MEADOW_CORE_DIR", os.path.join(REPOSITORY_ROOT, "..", "..", "meadow-3.0", "Meadow.Core")))
    for key, label in (("runtime_dir", "MEADOW_RUNTIME_DIR"), ("core_dir", "MEADOW_CORE_DIR")):
        if not os.path.isdir(settings[key]):
            sys.exit(f"No checkout at {settings[key]}; set {label}.")

    started = now()
    run_id = f"{started:%Y%m%d-%H%M%S}"
    run_dir = os.path.join(args.runs_dir, run_id)
    os.makedirs(run_dir)
    events = Events(os.path.join(run_dir, "events.jsonl"))

    run = {
        "id": run_id, "started": started.isoformat(timespec="seconds"), "finished": None,
        "manifest": os.path.relpath(args.manifest, REPOSITORY_ROOT), "cli": settings["cli"],
        "selected": [f"{t['name']}:{m}" for t, m in selected],
        "device": device_info(settings["cli"]),
        "sources": {
            "meadow_os": git_state(REPOSITORY_ROOT),
            "runtime": git_state(settings["runtime_dir"]),
            "meadow_core": git_state(settings["core_dir"]),
        },
    }
    device = run["device"]
    events.emit("run_started", f"{len(selected)} tests in {run_dir}; board OS {device.get('os', '?')}, runtime {device.get('runtime', '?')}, "
                f"coprocessor {device.get('coprocessor', '?')}")
    if "error" in device:
        events.emit("human_needed", f"device info failed: {device['error'][:200]}")

    results = []
    interrupted = False
    try:
        for test, mode in selected:
            results.append(run_test(test, mode, modes[mode].get("options", ""), settings, run_dir, events))
    except KeyboardInterrupt:
        interrupted = True
        events.emit("run_interrupted", "stopped by the user")

    run["finished"] = now().isoformat(timespec="seconds")
    run["totals"] = {verdict: sum(1 for r in results if r["verdict"] == verdict) for verdict in ("pass", "fail")}
    run["interrupted"] = interrupted
    with open(os.path.join(run_dir, "run.json"), "w", encoding="utf-8") as out:
        json.dump(run, out, indent=2)
    write_summary(run, results, os.path.join(run_dir, "summary.md"))
    events.emit("run_finished", f"pass={run['totals']['pass']} fail={run['totals']['fail']}; summary {os.path.join(run_dir, 'summary.md')}")
    events.close()
    return 0 if (not interrupted) and (run["totals"]["fail"] == 0) else 1


if __name__ == "__main__":
    sys.exit(main())
